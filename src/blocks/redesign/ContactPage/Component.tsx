/* ── The two states the mockup does not draw ──────────────────────────────
 *
 * The design has no error state and no sent state; it was drawn for a form that
 * handed the message to a mail app and never heard back. The shipped page has
 * both, and this block keeps its logic, so the two panels are mounted as
 * components beside the markup the mockup DOES draw.
 *
 * THE BUG THIS FIXES. On the contact page that ships today these two render as
 * WHITE TEXT ON A WHITE CARD. The cause is exact and is not a colour that was
 * chosen badly: `.ct-status`, `.ct-status--success` and `.ct-status--error` are
 * defined — with a readable green and red — in
 * src/blocks/contactBlocks/contact-template.css, and that file is imported only
 * by contactBlocks/ContactForm and contactBlocks/ContactSection.
 * src/blocks/ContactPage/Component.tsx styles itself with styled-jsx and
 * imports no stylesheet at all, so on the contact page those three class names
 * match no rule anywhere. The divs get no background and no colour, and
 * whatever light colour an ancestor supplies is what the visitor reads, against
 * `.ct-form-card { background: #fff }`.
 *
 * So these carry their colours in rd-ct.css, where the rest of this block's
 * layout lives, scoped to `.rd-ct` like every other rule in it. Both set
 * `color` AND `background` explicitly and inherit neither, so no ancestor —
 * including the Tailwind `prose-invert` the repo's own globals.css warns about
 * — can take them back to white.
 */
const CtStatus: React.FC<{ kind: 'sent' | 'error'; children?: React.ReactNode }> = ({
  kind,
  children,
}) => (
  <div className={`rd-ct-status rd-ct-status--${kind}`} role={kind === 'error' ? 'alert' : 'status'}>
    {children}
  </div>
)

/** The error, below the form. Renders nothing until there is one. */
const CtError: React.FC<{ msg?: string | null }> = ({ msg }) =>
  msg ? <CtStatus kind="error">{msg}</CtStatus> : null

/** The confirmation, in place of the form.
 *
 * The wording is the shipped page's own, verbatim. It is hardcoded English
 * there and stays hardcoded here, because this block was asked to keep that
 * logic — see the note in ship.json: on a nine-locale site these three strings
 * (this one and the two validation messages inside onSubmit) are the one part
 * of the form a German visitor reads in English. */
const CtSent: React.FC<{ show?: boolean }> = ({ show }) =>
  show ? (
    <CtStatus kind="sent">
      Thank you! Your message has been sent — we usually reply within 1–2 working days.
    </CtStatus>
  ) : null

