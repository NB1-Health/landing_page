/** A destination. The field holds a SLUG and the locale is added here, so one
 * stored value is right in all nine. Anything already absolute (a url, mailto,
 * tel, #anchor, or a /path) passes straight through, because an editor who
 * typed one meant it.
 *
 * `locale` is an ARGUMENT rather than a closure: this is module scope, and the
 * component that calls it is not the one that receives the prop. */
const liPath = (s?: string | null, locale?: string | null) => {
  const v = (s || '').trim()
  if (!v) return '#'
  if (/^(?:[a-z][a-z0-9+.-]*:|\/\/|\/|#)/i.test(v)) return v
  return `/${locale || 'en'}/${v}`
}

/** How many components belong to a family.
 *
 * COUNTED, NEVER TYPED. The mockup writes "All 96" on the first filter chip and
 * 19 / 12 / 21 / 44 on the four family tiles, and every one of those numbers is
 * the length of a list that is on the same page. A field would let an editor add
 * a 97th component and leave five numbers lying about it — the same reasoning
 * the FAQ block uses for its 01, 02 … group numbers: a number someone can get
 * out of step with the thing it counts is a number that will.
 *
 * (The hero's stat strip is NOT this. "~35 typically drawn per reading" and
 * "100% board-vetted" are claims, not counts, so all three of its figures stay
 * fields — including the 96, which sits beside them and would look odd as the
 * only derived one.) */
const liCount = (
  items?: ReadonlyArray<{ family?: string | null }> | null,
  family?: string | null,
) => (items || []).filter((x) => !family || x.family === family).length

/** The tint behind a component's picture.
 *
 * A FUNCTION OF THE FAMILY, not a field, and the mockup says so rather than
 * this deciding: all 96 card frames carry
 * `color-mix(in oklab, var(--nb1-X) 18%, #fff)`, and the four values of X fall
 * out exactly along the four families — lime on all 19 strains, orange on all
 * 12 fibres, blue-grey on all 21 vitamins and minerals, soft-pink on all 44
 * actives, checked card by card. So the colour is already saying what the
 * family is, and an editor filing a component under `fibres` should not also
 * have to remember that fibres are orange.
 *
 * The fallback is the warm grey every other empty frame on this design system
 * uses, for a row whose family has not been set yet. */
const LI_TINT: Record<string, string> = {
  strains: 'lime',
  fibres: 'orange',
  vitamins: 'blue-grey',
  actives: 'soft-pink',
}

const liTint = (family?: string | null) =>
  `color-mix(in oklab, var(--nb1-${LI_TINT[family || ''] || 'warm-grey'}) 18%, #fff)`

/** `Showing 7 of 96 components`, with the two numbers put back in.
 *
 * The line is a FIELD WITH PLACEHOLDERS rather than four fields glued together,
 * because the order of the numbers and the words between them is a sentence and
 * sentences do not survive being cut into pieces: German puts "von" where
 * English puts "of" and the Dutch count goes somewhere else again. One string
 * per locale, with `{shown}` and `{total}` wherever that locale wants them.
 *
 * A locale that drops a token simply renders without it, which is a translator's
 * decision and not this function's to override. */
const liShowing = (tpl: string | null | undefined, shown: number, total: number) =>
  (tpl || '').replace(/\{shown\}/g, String(shown)).replace(/\{total\}/g, String(total))

