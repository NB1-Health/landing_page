/** A destination. The field holds a SLUG and the locale is added here, so one
 * stored value is right in all nine. Anything already absolute (a url, mailto,
 * tel, #anchor, or a /path) passes straight through, because an editor who
 * typed one meant it.
 *
 * `locale` is an ARGUMENT rather than a closure: this is module scope, and the
 * component that calls it is not the one that receives the prop. */
const stPath = (s?: string | null, locale?: string | null) => {
  const v = (s || '').trim()
  if (!v) return '#'
  if (/^(?:[a-z][a-z0-9+.-]*:|\/\/|\/|#)/i.test(v)) return v
  return `/${locale || 'en'}/${v}`
}

/** A textarea read as a list, one item per line.
 *
 * Two fields on this page are lists that an array would have made impossible:
 * `plans.tiers[].features` would have produced
 * `_pages_v_blocks_rd_st_plans_tiers_features_locales_locale_parent_id` — 66
 * bytes, past the 63 Postgres truncates at SILENTLY — and `proof.docs[].rows`
 * was within three characters of the same cliff. Blank lines are dropped so a
 * trailing newline does not render an empty row. */
const stLines = (s?: string | null) =>
  (s || '').split('\n').map((l) => l.trim()).filter(Boolean)

/** The spec rows under a proof card: `Label | Value`, one pair per line.
 *
 * The separator is a pipe because no label or value on this page contains one,
 * and because a line that forgets it should still render something an editor
 * can see and fix — so a missing pipe gives the whole line as the label and an
 * empty value, rather than dropping the row. */
const stRows = (s?: string | null) =>
  stLines(s).map((l) => {
    const i = l.indexOf('|')
    return i === -1
      ? { label: l, value: '' }
      : { label: l.slice(0, i).trim(), value: l.slice(i + 1).trim() }
  })

