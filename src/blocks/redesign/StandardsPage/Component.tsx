/* ── Exported wrapper (amount tokens) ─────────────────────────────────
 *
 * The plan cards quote money — £99 and £149 a month, £94 and £144 on a
 * four-month cycle. The mockup is drawn in pounds, so seeded verbatim a German
 * visitor reads pounds, which is the fault already fixed on the order, checkout
 * and FAQ pages.
 *
 * So the seed carries tokens instead: `{{99}}`, `{{94}}`, `{{149}}`, `{{144}}`.
 * RenderBlocks already resolved the REFS before this block rendered —
 * `usePriceTokens` walks every block's props — but it resolves only `price:`
 * and `fee:`, because `hasToken()` tests for those two words. A plain amount
 * matches neither and would reach the page literally.
 *
 * So the amounts are resolved HERE, at the root, once, over the whole props
 * tree — and that is why it sits on RdSt rather than on RdStPlans, which is
 * where the prices actually render. RdSt hands `plans` down to RdStRest and
 * RdStRest hands it to RdStPlans, so resolving at the top means every section
 * below is handed values that are already right. A wrapper on RdStPlans would
 * work too and would have to be remembered the next time a section quotes a
 * number.
 *
 * See _shared/amountTokens.ts for why this is per-block rather than one line
 * in usePriceTokens.
 */
export const RdSt: React.FC<Props & { locale?: AppLocale }> = (props) => (
  <RdStInner {...useAmountTokens(props, props.locale)} />
)

