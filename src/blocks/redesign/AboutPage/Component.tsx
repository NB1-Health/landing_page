const mediaUrl = (m: unknown): string | undefined =>
  m && typeof m === 'object' && 'url' in m ? ((m as { url?: string }).url ?? undefined) : undefined

const mediaAlt = (m: unknown): string =>
  m && typeof m === 'object' && 'alt' in m ? ((m as { alt?: string }).alt ?? '') : ''

/* GENERATED into the block by --include — the two helpers its sections share.
 *
 * MODULE SCOPE, not a component body. The seven sections become seven
 * components in one module once tools/page_assemble.py has run, and a `const`
 * declared inside RdAb's body is not in scope in RdAbClose's. The Science
 * Board learned this the expensive way: the helpers went in `--body` and tsc
 * reported `Cannot find name 'locale'` three times, which was the right error
 * for the wrong reason — the fault was the scope, and the missing prop was
 * only the symptom.
 */

/** A destination. The field holds a SLUG and the locale is added here, so one
 * stored value is right in all nine. Anything already absolute (a url, mailto,
 * tel, #anchor, or a /path) passes straight through, because an editor who
 * typed one meant it.
 *
 * `locale` is an ARGUMENT rather than a closure: this is module scope, and the
 * component that calls it is not the one that receives the prop. */
const abPath = (s?: string | null, locale?: string | null) => {
  const v = (s || '').trim()
  if (!v) return '#'
  if (/^(?:[a-z][a-z0-9+.-]*:|\/\/|\/|#)/i.test(v)) return v
  return `/${locale || 'en'}/${v}`
}

/** An upload as a CSS `background-image` value.
 *
 * The two cards in "Two things had to exist" carry their picture as a
 * background on a `role="img"` div rather than as an <img>, so the upload
 * cannot be bound through `src`. It is bound through `styleVars`, which needs
 * the wrapped `url("…")` form — and needs `undefined`, not `url("")`, when
 * there is no media yet: an empty url() is a request for the current document,
 * which browsers will happily go and make. */
const abBg = (m: unknown): string | undefined => {
  const u = mediaUrl(m)
  return u ? `url("${u}")` : undefined
}

